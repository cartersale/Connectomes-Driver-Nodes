#!/usr/bin/env python
"""Recompute every number quoted in the paper from a run and write the number registry.

    python scripts/paper/key_numbers.py --run paper

Writes to <run>/paper/:
  key_results.json   {name: {value, text, source, locus, context}}: the exact (unrounded) values
  numbers.csv        one row per number: name, value, text, printed, locus, source, context
  numbers.tex        \\newcommand{\\<name>}{<text>} for every number, so the manuscript can use the macros

The registry modules are in scripts/paper/registry/ (one per part of the paper).
"""

from __future__ import annotations

import csv
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # registry/ and sections/

import registry  # noqa: E402

from hoc.runs import stage_from_argv  # noqa: E402

STAGE = "paper/numbers"
# paper/tables already requires most analysis stages; these are read only by the number registry.
REQUIRES = ("paper/tables", "mechanisms/01_hub_loading", "mechanisms/04_leading_eigenvectors", "mechanisms/05_second_subspace",
            "mechanisms/07_core_cut", "mechanisms/08_gramian_alignment", "concentration/06_er_avgctrl",
            "null_models/02_analyze", "null_models/00_validate", "primary/01_primary_analysis")


def write(numbers: list, out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    results = {
        n.name: {"value": None if math.isnan(n.value) else n.value, "text": n.text, "source": n.source,
                 "locus": list(n.locus), "context": n.context}
        for n in numbers
    }
    paths = [out / "key_results.json", out / "numbers.csv", out / "numbers.tex"]
    paths[0].write_text(json.dumps(results, indent=1, default=str) + "\n")
    with paths[1].open("w", newline="") as handle:
        w = csv.writer(handle)
        w.writerow(["name", "value", "text", "printed", "locus", "source", "context"])
        for n in numbers:
            ctx = {k: v for k, v in n.context.items() if k != "printed"}
            w.writerow([n.name, repr(n.value), n.text, n.context.get("printed", ""), ";".join(n.locus), n.source,
                        json.dumps(ctx, default=str, sort_keys=True)])
    lines = ["% Numbers quoted in the paper, generated by scripts/paper/key_numbers.py. Do not edit.", ""]
    section = None
    for n in numbers:
        if n.context.get("section") != section:
            section = n.context.get("section")
            lines += ["", f"% --- {section}"]
        lines.append(f"\\newcommand{{\\{n.name}}}{{{n.text}}}")
    paths[2].write_text("\n".join(lines).strip() + "\n")
    return paths


def main() -> None:
    ctx = stage_from_argv(STAGE)
    for upstream in REQUIRES:
        ctx.require_stage(upstream)
    ctx.begin()
    numbers = registry.collect(ctx.root)
    paths = write(numbers, ctx.root / "paper")
    missing = [n.name for n in numbers if math.isnan(n.value)]
    print(f"wrote {len(numbers)} numbers to {ctx.root / 'paper'}" + (f"; {len(missing)} have no source: {missing}" if missing else ""))
    ctx.finish(outputs=paths)


if __name__ == "__main__":
    main()
